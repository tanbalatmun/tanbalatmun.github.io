  const KEY = "tm_lang";
  let lang = "en";
  try { lang = localStorage.getItem(KEY) || "en"; } catch (e) {}
  if (lang !== "en" && lang !== "tr") lang = "en";

  const listeners = [];

  window.TM = window.TM || {};
  TM.i18n = {
    get lang() { return lang; },
    t(key) { return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key; },
    // Pick the right language out of a { en, tr } object.
    pick(obj) {
      if (obj == null) return "";
      if (typeof obj === "string") return obj;
      return obj[lang] || obj.en || "";
    },
    setLang(next) {
      if (next !== "en" && next !== "tr") return;
      lang = next;
      try { localStorage.setItem(KEY, next); } catch (e) {}
      TM.i18n.apply();
      listeners.forEach((fn) => fn(lang));
    },
    onChange(fn) { listeners.push(fn); },
    apply(root) {
      document.documentElement.lang = lang;
      (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = TM.i18n.t(el.dataset.i18n);
      });
      (root || document).querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.placeholder = TM.i18n.t(el.dataset.i18nPlaceholder);
      });
    },
  };
